import { expect, test } from '@playwright/test'

const sceneId = '11111111-1111-4111-8111-111111111111'

test('edits a PBR material, assigns it to one surface, and persists textures and UVs', async ({ page }) => {
  test.setTimeout(90_000)
  await page.goto('/')
  page.on('request', (request) => {
    if (request.url().includes(`/api/scenes/${sceneId}`) && request.method() === 'PUT') console.log('Scene PUT request started')
  })
  page.on('requestfailed', (request) => {
    if (request.url().includes(`/api/scenes/${sceneId}`)) console.log(`Scene request failed: ${request.failure()?.errorText ?? 'unknown'}`)
  })
  await expect(page.getByRole('heading', { name: 'Sample room' })).toBeVisible({ timeout: 20_000 })
  const before = await page.evaluate(async (id) => (await fetch(`/api/scenes/${id}`)).json(), sceneId)

  await page.getByRole('button', { name: /floor Floor/ }).click()
  const existingTestMaterial = page.getByRole('button', { name: 'Edit material E2E Travertine' }).first()
  if (await existingTestMaterial.count()) await existingTestMaterial.click()
  else await page.getByRole('button', { name: '+ New' }).click()
  await page.getByLabel('Material name').fill('E2E Travertine')
  const assignButton = page.getByRole('button', { name: 'Assign to selected surface' })
  if (await assignButton.isEnabled()) await assignButton.click()
  await page.getByLabel('Tile width (m)').fill('0.6')
  await page.getByLabel('Tile height (m)').fill('0.6')
  await page.getByRole('slider', { name: 'Roughness' }).fill('0.34')
  await page.getByRole('slider', { name: 'Metalness' }).fill('0.12')
  await page.getByLabel('Texture rotation').fill('45')
  await page.getByLabel('Texture offset U').fill('0.25')
  await page.getByLabel('Texture repeat U').fill('1.2')
  await page.getByLabel('Texture repeat V').fill('1.1')
  await page.getByLabel('Texture repeat V').press('Tab')
  await expect(page.getByText('Physical repeats: 8.00 × 6.60 across 4.00 × 3.60 m')).toBeVisible()
  const materialPreview = page.locator('.material-card.active .material-swatch')
  const originalPreview = await materialPreview.getAttribute('style')
  const uploadResponsePromise = page.waitForResponse((response) => response.url().includes('/api/assets/textures') && response.request().method() === 'POST')
  await page.getByLabel('Base color texture').scrollIntoViewIfNeeded()
  await page.getByLabel('Base color texture').setInputFiles({
    name: 'travertine.png', mimeType: 'image/png',
    buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAAAAAA6fptVAAAACklEQVR4nGNgAAAAAgABSK+kcQAAAABJRU5ErkJggg==', 'base64'),
  })
  const uploadResponse = await uploadResponsePromise
  expect(uploadResponse.status()).toBe(201)
  const uploadedTexture = await uploadResponse.json() as { url: string }
  await expect.poll(async () => materialPreview.getAttribute('style')).toContain(uploadedTexture.url)
  const normalMapResponsePromise = page.waitForResponse((response) => response.url().includes('/api/assets/textures') && response.request().method() === 'POST')
  await page.getByLabel('Normal map').scrollIntoViewIfNeeded()
  await page.getByLabel('Normal map').setInputFiles({
    name: 'travertine-normal.png', mimeType: 'image/png',
    buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAAAAAA6fptVAAAACklEQVR4nGNgAAAAAgABSK+kcQAAAABJRU5ErkJggg==', 'base64'),
  })
  const normalMapResponse = await normalMapResponsePromise
  expect(normalMapResponse.status()).toBe(201)

  await page.getByRole('button', { name: 'Undo edit' }).click()
  await expect.poll(async () => materialPreview.getAttribute('style')).toContain(uploadedTexture.url)
  await page.getByRole('button', { name: 'Undo edit' }).click()
  await expect.poll(async () => materialPreview.getAttribute('style')).toBe(originalPreview)
  await page.getByRole('button', { name: 'Redo edit' }).click()
  await expect.poll(async () => materialPreview.getAttribute('style')).toContain(uploadedTexture.url)
  await page.getByRole('button', { name: 'Redo edit' }).click()
  const saveResponsePromise = page.waitForResponse((response) => response.url().includes(`/api/scenes/${sceneId}`) && response.request().method() === 'PUT', { timeout: 20_000 })
  await page.getByRole('button', { name: 'Save scene' }).click()
  const saveResponse = await saveResponsePromise
  console.log(`Scene PUT completed with HTTP ${saveResponse.status()}`)
  await expect(page.getByText(/Saved to PostgreSQL · revision/)).toBeVisible()

  await page.reload()
  await expect(page.getByRole('heading', { name: 'Sample room' })).toBeVisible()
  await page.getByRole('button', { name: /floor Floor/ }).click()
  await page.getByRole('button', { name: 'Edit material E2E Travertine' }).first().click()
  await expect(page.getByLabel('Material name')).toHaveValue('E2E Travertine')
  await expect(page.getByLabel('Tile width (m)')).toHaveValue('0.6')
  await expect(page.getByRole('slider', { name: 'Roughness' })).toHaveValue('0.34')
  await expect(page.getByRole('slider', { name: 'Metalness' })).toHaveValue('0.12')
  await expect(page.getByLabel('Texture rotation')).toHaveValue('45')
  await expect(page.getByLabel('Texture offset U')).toHaveValue('0.25')
  await expect(page.getByLabel('Texture repeat U')).toHaveValue('1.2')
  await expect(page.getByLabel('Texture repeat V')).toHaveValue('1.1')
  await expect(page.getByText('Uploaded · replace')).toHaveCount(2)
  await expect(page.getByRole('button', { name: 'Assign to selected surface' })).toBeDisabled()

  const after = await page.evaluate(async (id) => (await fetch(`/api/scenes/${id}`)).json(), sceneId)
  expect(after.objects.map((object: { id: string }) => object.id)).toEqual(before.objects.map((object: { id: string }) => object.id))
  expect(after.objects.flatMap((object: { surfaces: { id: string }[] }) => object.surfaces.map((surface) => surface.id)))
    .toEqual(before.objects.flatMap((object: { surfaces: { id: string }[] }) => object.surfaces.map((surface) => surface.id)))
  const beforeWall = before.objects.flatMap((object: { surfaces: { semanticRole: string; materialId: string }[] }) => object.surfaces).find((surface) => surface.semanticRole === 'wall')
  const afterWall = after.objects.flatMap((object: { surfaces: { semanticRole: string; materialId: string }[] }) => object.surfaces).find((surface) => surface.semanticRole === 'wall')
  expect(afterWall.materialId).toBe(beforeWall.materialId)
  const floor = after.objects.flatMap((object: { surfaces: { semanticRole: string; materialId: string }[] }) => object.surfaces).find((surface) => surface.semanticRole === 'floor')
  const persistedMaterial = after.materials.find((material: { id: string; name: string }) => material.id === floor.materialId)
  expect(persistedMaterial?.name).toBe('E2E Travertine')
  expect(persistedMaterial?.maps.normal).toMatch(/^\/api\/assets\/textures\/[0-9a-f]{32}$/)
  const normalTextureStatus = await page.evaluate(async (url) => (await fetch(url)).status, persistedMaterial.maps.normal)
  expect(normalTextureStatus).toBe(200)
})

test('edits, hides, archives and restores objects without changing surface data', async ({ page }) => {
  test.setTimeout(90_000)
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Sample room' })).toBeVisible()
  const sceneId = '11111111-1111-4111-8111-111111111111'
  const before = await page.evaluate(async (id) => (await fetch(`/api/scenes/${id}`)).json(), sceneId)
  const originalCountertop = before.objects.find((object: { name: string }) => object.name === 'Countertop')
  const originalChair = before.objects.find((object: { name: string }) => object.name === 'Demo Chair Proxy')
  const originalCountertopRotationY = Math.round(Math.atan2(2 * originalCountertop.rotation[3] * originalCountertop.rotation[1], 1 - 2 * originalCountertop.rotation[1] ** 2) * 180 / Math.PI)
  const targetCountertopX = originalCountertop.position[0] === 0.95 ? 1.05 : 0.95
  const targetRotationY = originalCountertopRotationY === 30 ? 35 : 30
  const targetWidth = originalCountertop.dimensions[0] === 1.95 ? 2.05 : 1.95
  const targetHeight = originalCountertop.dimensions[1] === 0.07 ? 0.08 : 0.07
  const targetChairX = originalChair.position[0] === -1.1 ? -1.2 : -1.1
  const targetChairDepth = originalChair.dimensions[2] === 0.65 ? 0.7 : 0.65

  await page.getByRole('button', { name: 'Select object Countertop' }).click()
  await expect(page.getByRole('heading', { name: 'Countertop' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Delete Countertop' })).toBeDisabled()
  await expect(page.getByText('Structural objects are protected from deletion.')).toBeVisible()
  await page.getByLabel('Position X (m)').fill(String(targetCountertopX))
  await page.getByLabel('Position X (m)').press('Enter')
  await page.getByLabel('Position X (m)').blur()
  await expect(page.getByRole('button', { name: 'Undo edit' })).toBeEnabled()
  await page.getByRole('button', { name: 'Undo edit' }).click()
  await expect(page.getByLabel('Position X (m)')).toHaveValue(String(originalCountertop.position[0]))
  await page.getByRole('button', { name: 'Redo edit' }).click()
  await expect(page.getByLabel('Position X (m)')).toHaveValue(String(targetCountertopX))
  await page.getByRole('spinbutton', { name: 'Rotate Y (degrees)' }).fill(String(targetRotationY))
  await page.getByRole('spinbutton', { name: 'Rotate Y (degrees)' }).press('Enter')
  await page.getByRole('spinbutton', { name: 'Width (m)', exact: true }).fill(String(targetWidth))
  await page.getByRole('spinbutton', { name: 'Width (m)', exact: true }).press('Enter')
  await page.getByRole('spinbutton', { name: 'Height (m)', exact: true }).fill(String(targetHeight))
  await page.getByRole('spinbutton', { name: 'Height (m)', exact: true }).press('Enter')
  await page.getByRole('button', { name: 'Rotate gizmo' }).click()
  await expect(page.getByRole('button', { name: 'Rotate gizmo' })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Resize gizmo' }).click()
  await expect(page.getByRole('button', { name: 'Resize gizmo' })).toHaveAttribute('aria-pressed', 'true')

  await page.getByRole('button', { name: 'Select object Demo Chair Proxy' }).click()
  await expect(page.getByRole('heading', { name: 'Demo Chair Proxy' })).toBeVisible()
  await page.getByRole('button', { name: 'Hide Demo Chair Proxy' }).first().click()
  await expect(page.getByRole('button', { name: 'Show Demo Chair Proxy' }).first()).toBeVisible()
  await page.getByRole('button', { name: 'Undo edit' }).click()
  await expect(page.getByRole('button', { name: 'Hide Demo Chair Proxy' }).first()).toBeVisible()
  await page.getByRole('button', { name: 'Redo edit' }).click()
  await expect(page.getByRole('button', { name: 'Show Demo Chair Proxy' }).first()).toBeVisible()
  await page.getByRole('button', { name: 'Show Demo Chair Proxy' }).first().click()
  await page.getByLabel('Position X (m)').fill(String(targetChairX))
  await page.getByLabel('Position X (m)').press('Enter')
  await page.getByRole('spinbutton', { name: 'Depth (m)', exact: true }).fill(String(targetChairDepth))
  await page.getByRole('spinbutton', { name: 'Depth (m)', exact: true }).press('Enter')

  await page.getByRole('button', { name: 'Delete Demo Chair Proxy' }).first().click()
  await page.getByRole('alertdialog', { name: 'Confirm object deletion' }).getByRole('button', { name: 'Confirm delete' }).click()
  await expect(page.getByRole('button', { name: 'Restore Demo Chair Proxy' })).toBeVisible()
  await page.getByRole('button', { name: 'Undo edit' }).click()
  await expect(page.getByRole('button', { name: 'Select object Demo Chair Proxy' })).toBeVisible()
  await page.getByRole('button', { name: 'Redo edit' }).click()
  await expect(page.getByRole('button', { name: 'Restore Demo Chair Proxy' })).toBeVisible()
  const archiveSave = page.waitForResponse((response) => response.url().includes(`/api/scenes/${sceneId}`) && response.request().method() === 'PUT')
  await page.getByRole('button', { name: 'Save scene' }).click()
  expect((await archiveSave).status()).toBe(200)
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Sample room' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Restore Demo Chair Proxy' })).toBeVisible()
  await page.getByRole('button', { name: 'Restore Demo Chair Proxy' }).click()
  const restoreSave = page.waitForResponse((response) => response.url().includes(`/api/scenes/${sceneId}`) && response.request().method() === 'PUT')
  await page.getByRole('button', { name: 'Save scene' }).click()
  expect((await restoreSave).status()).toBe(200)
  await page.reload()
  await expect(page.getByRole('button', { name: 'Select object Demo Chair Proxy' })).toBeVisible()

  const after = await page.evaluate(async (id) => (await fetch(`/api/scenes/${id}`)).json(), sceneId)
  const countertop = after.objects.find((object: { id: string }) => object.id === originalCountertop.id)
  const chair = after.objects.find((object: { id: string }) => object.id === originalChair.id)
  expect(countertop.position).toEqual([targetCountertopX, ...originalCountertop.position.slice(1)])
  expect(countertop.dimensions).toEqual([targetWidth, targetHeight, ...originalCountertop.dimensions.slice(2)])
  expect(Math.round(Math.atan2(2 * countertop.rotation[3] * countertop.rotation[1], 1 - 2 * countertop.rotation[1] ** 2) * 180 / Math.PI)).toBe(targetRotationY)
  expect(countertop.surfaces).toEqual(originalCountertop.surfaces)
  expect(chair.position[0]).toBeCloseTo(targetChairX)
  expect(chair.dimensions[2]).toBeCloseTo(targetChairDepth)
  expect(chair.visible).toBe(true)
  expect(chair.id).toBe(originalChair.id)
  expect(after.deletedObjects).toEqual([])
})
